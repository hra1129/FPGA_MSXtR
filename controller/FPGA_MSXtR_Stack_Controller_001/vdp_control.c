void vdp_set_screen1_message(void) {
	char s_buffer[] = "FPGA MSXtR VDP/PICO Test.";

	vdp_set_vram_address( 0x1800 );
	vdp_write_vram( (uint8_t*) s_buffer, sizeof(s_buffer) );
}

